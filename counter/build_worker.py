"""
Builds worker.js - the file you paste into the Cloudflare dashboard - from:
    worker_src.js              the counters and the leaderboards
    the games' own code        so the server replays a game with exactly the code the page runs:
        ../breakout/docs/game.js, ../runner/docs/game.js, ../maze/docs/ship.js, ../car/docs/carsim.js
    ../car/docs/tracks.json    the car race's tracks (one leaderboard per track)

    python counter/build_worker.py

Run it again whenever one of these files changes (a change in a game's rules must reach the server too,
or the server's replay won't match the game in the browser).
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
GAMES = ["breakout/docs/game.js", "runner/docs/game.js", "maze/docs/ship.js", "car/docs/carsim.js"]


def main():
    parts = ["// =====================================================================================\n"
             "//  GENERATED by counter/build_worker.py - don't edit this file: edit worker_src.js and build again.\n"
             "//  Paste ALL of it into the Worker in the Cloudflare dashboard (Edit code), then Deploy.\n"
             "// =====================================================================================\n"]
    for g in GAMES:
        parts.append(f"\n// ----- {g} -----\n" + (ROOT / g).read_text())
    tracks = json.loads((ROOT / "car/docs/tracks.json").read_text())
    slim = {t["id"]: {"name": t["name"], "width": t["width"], "center": t["center"]} for t in tracks}
    parts.append("\n// ----- car/docs/tracks.json (the preset tracks) -----\nconst TRACKS = "
                 + json.dumps(slim, separators=(",", ":")) + ";\n")
    parts.append("\n// ----- worker_src.js -----\n" + (HERE / "worker_src.js").read_text())
    out = "".join(parts)
    (HERE / "worker.js").write_text(out)
    print(f"Wrote {HERE / 'worker.js'} ({len(out) / 1000:.0f} KB)")


if __name__ == "__main__":
    main()
